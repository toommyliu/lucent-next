use std::{env, fs, path::PathBuf};

use lucent_protocol::{
    aura::*, auth::*, event::*, hydration::*, item::*, monster_drop::*, packet::*, quest::*,
    readiness::*, shop::*, world::*,
};
use ts_rs::{Config, TS};

fn declarations(config: &Config) -> String {
    let mut output = String::from("// Generated by crates/protocol. Do not edit.\n\n");
    macro_rules! emit {
        ($($ty:ty),+ $(,)?) => { $(output.push_str("export "); output.push_str(&<$ty>::decl(config)); output.push('\n');)+ };
    }
    emit!(
        ServerData,
        ServerSnapshot,
        HydrationMethod,
        HydrationRequest,
        HydrationResult,
        ReadinessKey,
        ReadinessFlags,
        ReadinessSnapshot,
        PacketDirection,
        PacketEncoding,
        Packet,
        ItemContainer,
        ItemContext,
        Enhancement,
        ItemRequirement,
        ItemData,
        EnhancementSnapshot,
        ItemPool,
        ItemSnapshotFields,
        ItemSnapshot,
        MapState,
        Point,
        EntityKind,
        AuraKind,
        CounterSource,
        MessageSource,
        LocationChange,
        AuraEvent,
        ProjectionEvent,
        AuraValue,
        AuraData,
        EntityState,
        EntityData,
        EntitySnapshotFields,
        EntitySnapshot,
        PlayerData,
        PlayerSnapshot,
        MonsterData,
        MonsterSnapshot,
        QuestCadence,
        QuestItem,
        QuestReward,
        QuestData,
        ShopData,
        MonsterDrop
    );
    output.push_str(&format!(
        "\nexport const EntityState = {{ Dead: {}, Idle: {}, InCombat: {} }} as const;\n",
        i64::from(EntityState::Dead),
        i64::from(EntityState::Idle),
        i64::from(EntityState::InCombat),
    ));
    output
}

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let mut check = false;
    let mut path = None;
    for arg in env::args().skip(1) {
        if arg == "--check" {
            check = true;
        } else if path.is_none() {
            path = Some(PathBuf::from(arg));
        } else {
            return Err("Usage: export-types [--check] [output-path]".into());
        }
    }
    let path = path.unwrap_or_else(|| {
        PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../packages/game/src/protocol.ts")
    });
    let generated = declarations(&Config::new().with_large_int("number"));
    if check {
        if fs::read_to_string(&path)?.replace("\r\n", "\n") != generated {
            return Err(
                "Generated protocol declarations differ; run pnpm generate:protocol".into(),
            );
        }
    } else {
        if let Some(parent) = path.parent() {
            fs::create_dir_all(parent)?;
        }
        fs::write(&path, generated)?;
    }
    Ok(())
}
